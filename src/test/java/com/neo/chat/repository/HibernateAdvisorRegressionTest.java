    @Nested
    @DisplayName("bulk deletes remove exactly the rows the derived deleteBy methods removed")
    class BulkDeletes {

        @Test
        void deleteByUserAndFeatureKeyAndScopeIn_keepsSelfOptOutAndOtherUsers() {
            User target = user("grantee");
            User other = user("bystander");
            FeatureKey key = FeatureKey.values()[0];
            FeatureKey otherKey = FeatureKey.values()[1];
            em.persist(UserFeatureGrant.builder().user(target).featureKey(key).scope(GrantScope.ADMIN).build());
            em.persist(UserFeatureGrant.builder().user(target).featureKey(key).scope(GrantScope.COHORT).build());
            em.persist(UserFeatureGrant.builder().user(target).featureKey(key).scope(GrantScope.SELF).build());
            em.persist(UserFeatureGrant.builder().user(target).featureKey(otherKey).scope(GrantScope.ADMIN).build());
            em.persist(UserFeatureGrant.builder().user(other).featureKey(key).scope(GrantScope.ADMIN).build());
            freshContext();

            userFeatureGrantRepository.deleteByUserAndFeatureKeyAndScopeIn(
                    target, key, EnumSet.of(GrantScope.ADMIN, GrantScope.COHORT));
            em.clear();

            List<UserFeatureGrant> remaining = em.createQuery("select g from UserFeatureGrant g", UserFeatureGrant.class).getResultList();
            assertThat(remaining).hasSize(3);
            assertThat(remaining).filteredOn(g -> g.getUser().getId().equals(target.getId()) && g.getFeatureKey() == key)
                    .extracting(UserFeatureGrant::getScope).containsExactly(GrantScope.SELF);
        }

        @Test
        void deleteByWeekStartBefore_prunesOnlyOlderWeeks() {
            User a = user("wa");
            User b = user("wb");
            LocalDate monday = LocalDate.of(2026, 8, 31);
            em.persist(WeeklyMatchPick.builder().user(a).pickedUser(b).score(1).rank(1).weekStart(monday.minusWeeks(2)).build());
            em.persist(WeeklyMatchPick.builder().user(a).pickedUser(b).score(1).rank(1).weekStart(monday.minusWeeks(1)).build());
            em.persist(WeeklyMatchPick.builder().user(a).pickedUser(b).score(1).rank(1).weekStart(monday).build());
            freshContext();

            weeklyMatchPickRepository.deleteByWeekStartBefore(monday);
            em.clear();

            List<WeeklyMatchPick> remaining = em.createQuery("select p from WeeklyMatchPick p", WeeklyMatchPick.class).getResultList();
            assertThat(remaining).extracting(WeeklyMatchPick::getWeekStart).containsExactly(monday);
        }

        @Test
        void deleteByEndpoint_removesOnlyThatEndpoint() {
            User u = user("pusher");
            em.persist(PushSubscription.builder().user(u).endpoint("https://push/a").p256dh("k").auth("a")
                    .installationType(InstallationType.PWA).build());
            em.persist(PushSubscription.builder().user(u).endpoint("https://push/b").p256dh("k").auth("a")
                    .installationType(InstallationType.PWA).build());
            freshContext();

            pushSubscriptionRepository.deleteByEndpoint("https://push/a");
            em.clear();

            assertThat(pushSubscriptionRepository.findAll()).extracting(PushSubscription::getEndpoint)
                    .containsExactly("https://push/b");
        }

        @Test
        void userExperience_deleteByUser_removesOnlyThatUsersRows() {
            User u = user("exp1");
            User other = user("exp2");
            em.persist(UserExperience.builder().user(u).tag("hiking").build());
            em.persist(UserExperience.builder().user(u).tag("chess").build());
            em.persist(UserExperience.builder().user(other).tag("hiking").build());
            freshContext();

            userExperienceRepository.deleteByUser(u);
            em.clear();

            List<UserExperience> remaining = userExperienceRepository.findAll();
            assertThat(remaining).hasSize(1);
            assertThat(remaining.get(0).getUser().getId()).isEqualTo(other.getId());
        }

        @Test
        void session_deleteByUser_removesOnlyThatUsersRows() {
            User u = user("sess1");
            User other = user("sess2");
            em.persist(Session.builder().user(u).userAgent("ua").build());
            em.persist(Session.builder().user(u).userAgent("ua").build());
            em.persist(Session.builder().user(other).userAgent("ua").build());
            freshContext();

            sessionRepository.deleteByUser(u);
            em.clear();

            List<Session> remaining = sessionRepository.findAll();
            assertThat(remaining).hasSize(1);
            assertThat(remaining.get(0).getUser().getId()).isEqualTo(other.getId());
        }

        @Test
        void deleteByMessageAndUser_removesOnlyThatStar() {
            User u = user("star1");
            User other = user("star2");
            Message m1 = message(u);
            Message m2 = message(u);
            em.persist(MessageStar.builder().message(m1).user(u).build());
            em.persist(MessageStar.builder().message(m1).user(other).build());
            em.persist(MessageStar.builder().message(m2).user(u).build());
            freshContext();

            messageStarRepository.deleteByMessageAndUser(m1, u);
            em.clear();

            List<MessageStar> remaining = messageStarRepository.findAll();
            assertThat(remaining).hasSize(2);
            Set<String> keys = new HashSet<>();
            remaining.forEach(s -> keys.add(s.getMessage().getId() + ":" + s.getUser().getId()));
            assertThat(keys).containsExactlyInAnyOrder(m1.getId() + ":" + other.getId(), m2.getId() + ":" + u.getId());
        }
    }

