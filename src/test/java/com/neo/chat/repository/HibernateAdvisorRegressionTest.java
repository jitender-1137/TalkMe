    @Nested
    @DisplayName("PostRepository fetch-joins Post.poll")
    class PostQueries {

        @Test
        void findVisibleFeedFor_loadsPollInTheSameSelect() {
            User viewer = user("viewer");
            post(viewer, null, "Q1");
            post(viewer, null, null);
            post(viewer, null, "Q3");
            freshContext();

            Page<Post> page = postRepository.findVisibleFeedFor(viewer, PageRequest.of(0, 10));

            assertThat(page.getTotalElements()).isEqualTo(3);
            assertThat(page.getContent()).hasSize(3);
            assertThat(page.getContent()).allSatisfy(p -> assertThat(Hibernate.isInitialized(p.getPoll())).isTrue());
            assertThat(page.getContent()).filteredOn(p -> p.getPoll() != null)
                    .extracting(p -> p.getPoll().getQuestion()).containsExactlyInAnyOrder("Q1", "Q3");
            assertThat(statistics.getEntityFetchCount()).as("secondary entity selects").isZero();
        }

        @Test
        void findProfileFeedFor_loadsPollInTheSameSelect() {
            User target = user("target");
            User viewer = user("viewer2");
            post(target, null, "Public poll");
            post(target, null, null);
            freshContext();

            Page<Post> page = postRepository.findProfileFeedFor(target, viewer, PageRequest.of(0, 10));

            assertThat(page.getTotalElements()).isEqualTo(2);
            assertThat(page.getContent()).allSatisfy(p -> assertThat(Hibernate.isInitialized(p.getPoll())).isTrue());
            assertThat(statistics.getEntityFetchCount()).isZero();
        }

        @Test
        void findFeedForUser_loadsPollInTheSameSelect() {
            User me = user("me");
            User stranger = user("stranger");
            post(me, null, "Mine");
            post(stranger, null, "Not followed");
            freshContext();

            Page<Post> page = postRepository.findFeedForUser(me, PageRequest.of(0, 10));

            assertThat(page.getTotalElements()).isEqualTo(1);
            assertThat(page.getContent().get(0).getPoll().getQuestion()).isEqualTo("Mine");
            assertThat(statistics.getEntityFetchCount()).isZero();
        }

        @Test
        void findExpiredActive_loadsPollInTheSameSelect() {
            User author = user("author");
            Instant now = Instant.now();
            post(author, now.minus(2, ChronoUnit.HOURS), "Expired A");
            post(author, now.minus(1, ChronoUnit.HOURS), null);
            post(author, now.plus(1, ChronoUnit.HOURS), "Still live");
            freshContext();

            List<Post> expired = postRepository.findExpiredActive(now, PageRequest.of(0, 10));

            assertThat(expired).hasSize(2);
            assertThat(expired.get(0).getPoll().getQuestion()).isEqualTo("Expired A");
            assertThat(expired.get(1).getPoll()).isNull();
            assertThat(statistics.getEntityFetchCount()).isZero();
        }
    }

    @Nested
    @DisplayName("UserRepository fetch-joins User.presence")
    class UserQueries {

        @Test
        void findAllOnlineUsersExcludeSelf_loadsPresenceInTheSameSelect() {
            User self = user("self");
            User online = user("online");
            User offline = user("offline");
            presence(self, "ONLINE");
            presence(online, "ONLINE");
            presence(offline, "OFFLINE");
            Long selfId = self.getId();
            freshContext();

            List<User> result = userRepository.findAllOnlineUsersExcludeSelf(selfId);

            assertThat(result).extracting(User::getUsername).containsExactly("online");
            assertThat(Hibernate.isInitialized(result.get(0).getPresence())).isTrue();
            assertThat(result.get(0).getPresence().getStatus()).isEqualTo("ONLINE");
            assertThat(statistics.getEntityFetchCount()).isZero();
        }

        @Test
        void findAllByUsernameInExcludeSelf_loadsPresenceInTheSameSelect() {
            User self = user("alpha");
            User other = user("beta");
            user("gamma");
            presence(other, "IDLE");
            Long selfId = self.getId();
            freshContext();

            List<User> result = userRepository.findAllByUsernameInExcludeSelf(Set.of("alpha", "beta"), selfId);

            assertThat(result).extracting(User::getUsername).containsExactly("beta");
            assertThat(result.get(0).getPresence().getStatus()).isEqualTo("IDLE");
            assertThat(statistics.getEntityFetchCount()).isZero();

            statistics.clear();
            // null currentUserId => no self exclusion; a user without a presence row still comes back.
            List<User> all = userRepository.findAllByUsernameInExcludeSelf(Set.of("alpha", "gamma"), null);
            assertThat(all).extracting(User::getUsername).containsExactlyInAnyOrder("alpha", "gamma");
            assertThat(all).allSatisfy(u -> assertThat(u.getPresence()).isNull());
            assertThat(statistics.getEntityFetchCount()).isZero();
        }

        @Test
        void findAccountsDueForPurge_loadsPresenceInTheSameSelect() {
            Instant cutoff = Instant.now().minus(30, ChronoUnit.DAYS);
            User due = user("due");
            due.setDeleted(true);
            due.setDeletionRequestedAt(cutoff.minus(1, ChronoUnit.DAYS));
            User recent = user("recent");
            recent.setDeleted(true);
            recent.setDeletionRequestedAt(cutoff.plus(1, ChronoUnit.DAYS));
            user("active");
            presence(due, "OFFLINE");
            freshContext();

            List<User> result = userRepository.findAccountsDueForPurge(cutoff);

            assertThat(result).extracting(User::getUsername).containsExactly("due");
            assertThat(result.get(0).getPresence().getStatus()).isEqualTo("OFFLINE");
            assertThat(statistics.getEntityFetchCount()).isZero();
        }
    }

