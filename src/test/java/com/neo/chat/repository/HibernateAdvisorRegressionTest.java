    @Test
    @DisplayName("every foreign key column is the leading column of a declared index or unique constraint")
    void everyForeignKeyHasASupportingIndex() throws Exception {
        List<String> unsupported = new ArrayList<>();
        try (Connection c = dataSource.getConnection()) {
            DatabaseMetaData md = c.getMetaData();
            List<String> tables = new ArrayList<>();
            try (ResultSet rs = md.getTables(null, "PUBLIC", "%", new String[]{"TABLE", "BASE TABLE"})) {
                while (rs.next()) {
                    tables.add(rs.getString("TABLE_NAME"));
                }
            }
            assertThat(tables).as("Hibernate generated the schema").isNotEmpty();
            for (String table : tables) {
                // FK constraint name -> ordered FK columns
                Map<String, TreeMap<Integer, String>> fks = new HashMap<>();
                try (ResultSet rs = md.getImportedKeys(null, "PUBLIC", table)) {
                    while (rs.next()) {
                        fks.computeIfAbsent(rs.getString("FK_NAME"), k -> new TreeMap<>())
                                .put(rs.getInt("KEY_SEQ"), rs.getString("FKCOLUMN_NAME").toUpperCase(Locale.ROOT));
                    }
                }
                if (fks.isEmpty()) {
                    continue;
                }
                // index name -> ordered columns. H2 silently creates its own backing index for a
                // referential constraint when none exists (named <FK_NAME>_INDEX_n); those are
                // excluded so the check reflects only what the mapping declares (what PostgreSQL gets).
                Map<String, TreeMap<Integer, String>> indexes = new HashMap<>();
                try (ResultSet rs = md.getIndexInfo(null, "PUBLIC", table, false, false)) {
                    while (rs.next()) {
                        String name = rs.getString("INDEX_NAME");
                        String col = rs.getString("COLUMN_NAME");
                        if (name == null || col == null) {
                            continue;
                        }
                        boolean h2FkBacking = fks.keySet().stream()
                                .anyMatch(fk -> name.toUpperCase(Locale.ROOT).startsWith(fk.toUpperCase(Locale.ROOT)));
                        if (h2FkBacking) {
                            continue;
                        }
                        indexes.computeIfAbsent(name, k -> new TreeMap<>())
                                .put(rs.getInt("ORDINAL_POSITION"), col.toUpperCase(Locale.ROOT));
                    }
                }
                for (Map.Entry<String, TreeMap<Integer, String>> fk : fks.entrySet()) {
                    List<String> fkCols = new ArrayList<>(fk.getValue().values());
                    boolean covered = indexes.values().stream()
                            .map(m -> new ArrayList<>(m.values()))
                            .anyMatch(idx -> idx.size() >= fkCols.size() && idx.subList(0, fkCols.size()).equals(fkCols));
                    if (!covered) {
                        unsupported.add(table + fkCols);
                    }
                }
            }
        }
        assertThat(unsupported).as("foreign keys without a supporting index").isEmpty();
    }

