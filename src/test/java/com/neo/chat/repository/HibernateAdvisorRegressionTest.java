    @Nested
    @DisplayName("@NaturalId on BaseEntity#uuid resolves through the @MappedSuperclass")
    class NaturalId {

        @Test
        void uuidIsAssignedOnPersistAndResolvesAsNaturalId() {
            User u = user("natural");
            assertThat(u.getUuid()).as("@PrePersist assigned the uuid before Hibernate captured state").isNotNull();
            UUID uuid = u.getUuid();
            freshContext();

            User byNaturalId = em.unwrap(org.hibernate.Session.class).bySimpleNaturalId(User.class).load(uuid);

            assertThat(byNaturalId).isNotNull();
            assertThat(byNaturalId.getId()).isEqualTo(u.getId());
            assertThat(byNaturalId.getUsername()).isEqualTo("natural");
        }

        @Test
        void explicitUuidOnANewEntityIsKept() {
            UUID explicit = UUID.randomUUID();
            Chat chat = Chat.builder().build();
            chat.setUuid(explicit);
            persist(chat);
            freshContext();

            assertThat(em.unwrap(org.hibernate.Session.class).bySimpleNaturalId(Chat.class).load(explicit).getId())
                    .isEqualTo(chat.getId());
            assertThat(em.find(Chat.class, chat.getId()).getUuid()).isEqualTo(explicit);
        }
    }

