    @Nested
    @DisplayName("Set<Enum> element-collection tables get a composite primary key")
    class ElementCollectionPrimaryKeys {

        private List<String> primaryKeyColumns(String table) throws Exception {
            try (Connection c = dataSource.getConnection();
                 ResultSet rs = c.getMetaData().getPrimaryKeys(null, "PUBLIC", table.toUpperCase(Locale.ROOT))) {
                TreeMap<Integer, String> cols = new TreeMap<>();
                while (rs.next()) {
                    cols.put(rs.getInt("KEY_SEQ"), rs.getString("COLUMN_NAME").toLowerCase(Locale.ROOT));
                }
                return new ArrayList<>(cols.values());
            }
        }

        @Test
        void chatTagsUserLanguagesAndUserLookingForHaveAPrimaryKey() throws Exception {
            assertThat(primaryKeyColumns("chat_tags")).containsExactly("chat_id", "tag");
            assertThat(primaryKeyColumns("user_languages")).containsExactly("user_id", "language");
            assertThat(primaryKeyColumns("user_looking_for")).containsExactly("user_id", "tag");
        }

        @Test
        void setElementsStillRoundTrip() {
            User u = user("polyglot");
            u.getLanguages().addAll(Set.of(Language.values()[0], Language.values()[1]));
            u.getLookingFor().add(LookingForTag.values()[0]);
            Chat chat = persist(Chat.builder().build());
            chat.getTags().add(Interest.values()[0]);
            freshContext();

            User reloaded = em.find(User.class, u.getId());
            assertThat(reloaded.getLanguages()).containsExactlyInAnyOrder(Language.values()[0], Language.values()[1]);
            assertThat(reloaded.getLookingFor()).containsExactly(LookingForTag.values()[0]);
            assertThat(em.find(Chat.class, chat.getId()).getTags()).containsExactly(Interest.values()[0]);
        }
    }
