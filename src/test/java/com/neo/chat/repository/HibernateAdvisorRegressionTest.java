    // ── fixtures ─────────────────────────────────────────────────────────────────────

    private <T> T persist(T entity) {
        em.persist(entity);
        return entity;
    }

    private User user(String username) {
        return persist(User.builder()
                .username(username)
                .email(username + "@example.com")
                .name("User " + username)
                .isGuest(false)
                .isVerified(true)
                .build());
    }

    private UserPresence presence(User user, String status) {
        return persist(UserPresence.builder().user(user).status(status).build());
    }

    private Post post(User author, Instant expiresAt, String pollQuestion) {
        Post post = persist(Post.builder().user(author).content("hello").expiresAt(expiresAt).build());
        if (pollQuestion != null) {
            persist(Poll.builder().post(post).question(pollQuestion).build());
        }
        return post;
    }

    private Message message(User sender) {
        Chat chat = persist(Chat.builder().build());
        return persist(Message.builder().chat(chat).sender(sender).content("m").build());
    }

    /** Flush pending writes, clear the persistence context and reset Hibernate statistics. */
    private void freshContext() {
        em.flush();
        em.clear();
        statistics.clear();
    }

