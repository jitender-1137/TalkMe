/**
 * Regression coverage for the BootUI Hibernate/Database Advisor fixes (2026-09-07):
 *
 * <ul>
 *   <li>DB-SCHEMA-002 / HIB-MAP-019 — every foreign key column is the leading column of a declared
 *       index or unique constraint. The whole schema is generated by Hibernate ({@code create-drop})
 *       from the entity annotations, so this is checked against real JDBC metadata rather than by
 *       re-parsing annotations.</li>
 *   <li>HIB-QUERY-005 — the entity-returning {@code @Query} methods on {@link PostRepository} and
 *       {@link UserRepository} now {@code LEFT JOIN FETCH} their eager to-one association
 *       ({@code Post.poll}, {@code User.presence}), so Hibernate no longer issues one secondary
 *       select per returned row. Verified through {@link Statistics#getEntityFetchCount()}.</li>
 *   <li>HIB-QUERY-004 — the six former derived {@code deleteBy…} methods are now single-statement
 *       JPQL bulk deletes; they must remove exactly the rows the derived variants removed.</li>
 * </ul>
 *
 * <p>Booting the context at all also validates every new {@code @Index}: an unknown column or a
 * duplicated index name fails schema generation ({@code ddl-auto: create-drop} on H2 in the
 * {@code test} profile). The build has no {@code spring-boot-data-jpa-test} slice module, so this
 * uses the same full-context bootstrap as the controller tests; every test rolls back.
 */
